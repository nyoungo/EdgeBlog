/** Map a social link type to an icon (falls back to a generic link glyph). */
export function socialIcon(type: string): IconName {
  switch (type) {
    case 'github':
      return 'github';
    case 'x':
      return 'twitter';
    case 'email':
      return 'mail';
    case 'rss':
      return 'rss';
    case 'linkedin':
      return 'linkedin';
    case 'youtube':
      return 'youtube';
    default:
      return 'link';
  }
}
